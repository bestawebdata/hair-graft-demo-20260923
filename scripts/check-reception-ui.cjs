const { JSDOM, VirtualConsole } = require(process.env.DEMO_JSDOM || 'jsdom');
const assert = require('node:assert/strict'), path = require('node:path');
(async () => {
  const errors = [], vc = new VirtualConsole(); vc.on('jsdomError', e => errors.push(e.message));
  const dom = await JSDOM.fromFile(path.resolve(__dirname, '../dist/coordination/index.html'), { resources: 'usable', runScripts: 'dangerously', pretendToBeVisual: true, virtualConsole: vc });
  await new Promise(r => dom.window.addEventListener('load', r));
  const w = dom.window, d = w.document, $ = s => d.querySelector(s), snap = () => w.CoordinationDemo.snapshot(); let count = 0;
  const check = (ok, message) => { assert(ok, message); count++; console.log('PASS ' + message); };
  const click = s => { assert($(s), s); $(s).click(); };
  const submit = s => $(s).dispatchEvent(new w.Event('submit', { bubbles: true, cancelable: true }));
  const change = (s, value) => { $(s).value = value; $(s).dispatchEvent(new w.Event('change', { bubbles: true })); };
  click('[data-view=reception]'); click('[data-action=reception-sample]'); click('[data-action=reception-load]');
  check(!$('#reception-view').hidden && d.querySelectorAll('.reception-card').length === 8, '8人の受付例へ切替');
  check(d.querySelectorAll('.reception-card.proposed').length === 5, '5人の案内候補と理由を表示');
  check($('.reception-card[data-patient=P08] [data-action=intake-message]').disabled, '案内停止した方の文面生成を停止');
  click('.reception-card[data-patient=P06] [data-action=intake-message]');
  check($('#modal-body textarea').value.includes('担当者が確認') && $('#modal-body textarea').value.includes('送信されていません'), '相談の方には相談対応の文面を作成');
  click('#close-modal'); click('.reception-card[data-patient=P01] [data-action=intake-edit]');
  change('#intake-form [name=readiness]', 'consult'); submit('#intake-form');
  check(d.querySelectorAll('.reception-card.proposed').length === 4 && $('#reception-view [data-action=confirm]').disabled, '本人希望の変更で候補と開催可否を更新');
  click('[data-view=patient]'); change('#patient-select', 'P01');
  check($('#patient-intake-form [name=readiness]').value === 'consult', '患者側に本人の希望を反映');
  change('#patient-intake-form [name=readiness]', 'ready'); submit('#patient-intake-form'); click('[data-view=reception]');
  check(d.querySelectorAll('.reception-card.proposed').length === 5, '患者本人が希望を変更して候補に復帰');
  click('#reception-view [data-action=confirm]');
  check([...d.querySelectorAll('[name=participants]:checked')].map(x => x.value).join(',') === 'P01,P03,P02,P04,P05', '提案順の5人を開催確認へ引継ぎ');
  submit('#confirm-form'); check(snap().events[0].participants.length === 5 && $('#reception-view').textContent.includes('次の募集日程'), '開催確定後に同じ募集の新規案内を終了');
  click('[data-view=patient]'); check(!$('#patient-intake-form'), '確定後の変更は個別対応として表示');
  check(errors.length === 0, '受付画面のDOM実行エラーなし');
  dom.window.close(); console.log(`${count} reception UI checks passed.`);
})().catch(e => { console.error(e); process.exit(1); });
